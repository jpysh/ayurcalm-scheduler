// node scripts/uat-1016.mjs — a starter in use offers Update with its name, at 375x812 (#1016). E2E_BASE_URL picks the stack.
import { chromium } from '@playwright/test';
import { mkdirSync } from 'node:fs';
const APP = process.env.E2E_BASE_URL || 'http://localhost:8080';
const OUT = 'docs/design/uat/2026-10-19-update-starter-1016';
mkdirSync(OUT, { recursive: true });
const { token } = await (await fetch(`${APP}/api/auth/login`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ email: 'admin@example.com', password: 'demo1234' }) })).json();
const api = (path, body) => fetch(`${APP}/api${path}`, { method: body ? 'POST' : 'GET', headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${token}` }, body: body && JSON.stringify(body) }).then((r) => r.json());
const day = (n) => new Date(Date.now() + n * 86400000).toLocaleDateString('en-CA', { timeZone: 'Asia/Kolkata' });
if (!(await api('/patients')).some((x) => x.name === 'Nisha Kapoor')) await api('/patients', { name: 'Nisha Kapoor', gender: 'female', stay: { start_date: day(0), end_date: day(10) } });
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 375, height: 812 }, hasTouch: true, isMobile: true });
await ctx.addInitScript((t) => { localStorage.setItem('authToken', t); localStorage.setItem('authRole', 'Admin'); localStorage.setItem('authUser', 'admin@example.com'); }, token);
const p = await ctx.newPage();
await p.goto(`${APP}/admin/patients`); await p.waitForTimeout(2500);
await p.getByText('Nisha Kapoor').first().click(); await p.waitForTimeout(1500);
await p.getByRole('button', { name: 'Plan next week' }).click(); await p.waitForTimeout(2500);
await p.getByRole('button', { name: /Back pain/ }).click(); await p.waitForTimeout(800);
await p.getByRole('button', { name: 'Update', exact: true }).scrollIntoViewIfNeeded(); await p.waitForTimeout(500);
await p.screenshot({ path: `${OUT}/after-update-375.png` });
await b.close();
