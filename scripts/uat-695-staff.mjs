// E2E_BASE_URL=http://localhost:8097 node scripts/uat-695-staff.mjs — #695 part 6: Team is Staff. 375x812.
import { chromium } from '@playwright/test';
import { mkdirSync, writeFileSync } from 'node:fs';
const APP = process.env.E2E_BASE_URL || 'http://localhost:8080';
const OUT = 'docs/design/uat/2026-10-09-staff-rename';
mkdirSync(OUT, { recursive: true });
const { token } = await (await fetch(`${APP}/api/auth/login`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ email: 'admin@example.com', password: 'demo1234' }) })).json();
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 375, height: 812 }, hasTouch: true, isMobile: true });
await ctx.addInitScript((t) => { localStorage.setItem('authToken', t); localStorage.setItem('authRole', 'Admin'); localStorage.setItem('authUser', 'admin@example.com'); }, token);
const p = await ctx.newPage();
const res = [];
const check = (name, ok) => { res.push([name, ok]); console.log(ok ? 'pass' : 'FAIL', name); };
await p.goto(`${APP}/admin/schedule`); await p.waitForTimeout(2500);
await p.getByRole('button', { name: 'Menu' }).click(); await p.waitForTimeout(700);
await p.screenshot({ path: `${OUT}/01-menu.png` });
const menu = await p.getByRole('dialog').last().innerText();
check('the menu says Staff, not Team', /\bStaff\b/.test(menu) && !/\bTeam\b/.test(menu));
await p.getByRole('dialog').last().getByRole('button', { name: /^Staff/ }).click(); await p.waitForTimeout(2000);
await p.screenshot({ path: `${OUT}/02-staff.png` });
check('the screen is headed Staff', (await p.getByRole('heading', { name: 'Staff' }).count()) >= 1);
writeFileSync(`${OUT}/README.md`, `# #695 part 6 UAT, 9 Oct (demo seed)\n\n| Step | Result |\n|---|---|\n${res.map(([n, ok]) => `| ${n} | ${ok ? 'pass' : 'FAIL'} |`).join('\n')}\n\n![](01-menu.png) ![](02-staff.png)\n`);
await b.close();
process.exit(res.every(([, ok]) => ok) ? 0 : 1);
