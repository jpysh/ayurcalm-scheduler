import { chromium } from '@playwright/test';
import { mkdirSync } from 'node:fs';
const APP = process.env.E2E_BASE_URL || 'http://localhost:8080';
const OUT = 'docs/design/uat/2026-10-18-settings-refusals-949';
mkdirSync(OUT, { recursive: true });
const { token } = await (await fetch(`${APP}/api/auth/login`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ email: 'admin@example.com', password: 'demo1234' }) })).json();
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 375, height: 812 }, hasTouch: true, isMobile: true });
await ctx.addInitScript((t) => { localStorage.setItem('authToken', t); localStorage.setItem('authRole', 'Admin'); }, token);
const p = await ctx.newPage();
await p.goto(`${APP}/admin/settings`); await p.waitForTimeout(2000);
await p.getByText('Centre and letterhead').first().click(); await p.waitForTimeout(800);
await p.locator('#lh_website').fill('javascript:alert(1)');
await p.locator('#lh_email').fill('not-an-email');
await p.getByRole('button', { name: 'Save' }).click(); await p.waitForTimeout(800);
await p.locator('#lh_website').scrollIntoViewIfNeeded();
await p.screenshot({ path: `${OUT}/after-website.png` });
await p.goto(`${APP}/setup/mine`); await p.waitForTimeout(1500);
await p.locator('textarea').nth(1).fill('Asha, Ravi, Meera'); await p.waitForTimeout(400);
await p.locator('textarea').nth(1).scrollIntoViewIfNeeded();
await p.screenshot({ path: `${OUT}/after-list.png` });
await b.close();
