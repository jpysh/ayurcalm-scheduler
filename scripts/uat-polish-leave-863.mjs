// node scripts/uat-polish-leave-863.mjs before|after — #863 at 375x812: the toast after Save and fix the day, the picker's guests group.
import { chromium } from '@playwright/test';
import { mkdirSync } from 'node:fs';
const APP = process.env.E2E_BASE_URL || 'http://localhost:8080';
const WHEN = process.argv[2] || 'after';
const OUT = 'docs/design/uat/polish-leave-863';
mkdirSync(OUT, { recursive: true });
const { token } = await (await fetch(`${APP}/api/auth/login`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ email: 'admin@example.com', password: 'demo1234' }) })).json();
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 375, height: 812 }, hasTouch: true, isMobile: true });
await ctx.addInitScript((t) => { localStorage.setItem('authToken', t); localStorage.setItem('authRole', 'Admin'); localStorage.setItem('authUser', 'admin@example.com'); }, token);
const p = await ctx.newPage();
const dlg = () => p.getByRole('dialog').last();
await p.goto(`${APP}/admin/timeoff`); await p.waitForTimeout(1600);
await p.getByRole('navigation', { name: 'Main' }).getByRole('button').first().click(); await p.waitForTimeout(800);
await p.screenshot({ path: `${OUT}/picker-${WHEN}.png` });
await dlg().getByText('Show staff').click(); await p.waitForTimeout(300);
await dlg().getByRole('checkbox').nth(4).click();
await dlg().getByRole('button', { name: /^Next/ }).click(); await p.waitForTimeout(1200);
await dlg().getByRole('button', { name: /^Save and fix/ }).click(); await p.waitForTimeout(1500);
await p.screenshot({ path: `${OUT}/plan-toast-${WHEN}.png` });
await p.locator('[data-sonner-toast]').getByRole('button', { name: 'Undo' }).click();
await b.close();
