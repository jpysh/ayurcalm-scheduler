// node scripts/uat-1199.mjs — A late checkout time, shown on Guest rooms (#1200), 375x812, on a throwaway stack (APP_URL).
import { chromium } from '@playwright/test';
import { mkdirSync } from 'node:fs';
const APP = process.env.APP_URL || 'http://localhost:8391';
const OUT = 'docs/design/uat/2026-10-28-late-checkout';
mkdirSync(OUT, { recursive: true });
const { token } = await (await fetch(`${APP}/api/auth/login`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ email: 'admin@example.com', password: 'demo1234' }) })).json();
const today = new Intl.DateTimeFormat('en-CA', { timeZone: 'Asia/Kolkata' }).format(new Date());
const add = (n) => new Date(Date.parse(`${today}T00:00:00Z`) + n * 86400000).toISOString().slice(0, 10);
const api = (m, p, b) => fetch(`${APP}/api${p}`, { method: m, headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${token}` }, body: b ? JSON.stringify(b) : undefined }).then((r) => r.json());
const room = (await api('GET', `/guest-rooms/free?from=${add(-3)}&to=${add(0)}`)).find((r) => r.free);
await api('POST', '/patients', { name: 'Uat Late Checkout', gender: 'female', on_site: true, guest_room_id: room.id, stay: { start_date: add(-3), end_date: add(0) } });
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 375, height: 812 }, hasTouch: true, isMobile: true, timezoneId: 'Asia/Kolkata' });
await ctx.addInitScript((t) => { localStorage.setItem('authToken', t); localStorage.setItem('authRole', 'Admin'); localStorage.setItem('authUser', 'admin@example.com'); }, token);
const p = await ctx.newPage();
await p.goto(`${APP}/admin/guestrooms`); await p.waitForTimeout(2500);
const g = (await api('GET', `/guest-rooms/free?from=${today}&to=${add(1)}`)).flatMap((r) => r.guests).find((x) => x.name === 'Uat Late Checkout');
await api('PUT', `/patients/${g.patient_id}/stays/${g.stay_id}`, { leaving_time: '15:00' });
await p.reload(); await p.waitForTimeout(2500);
const row = p.getByText('Uat Late Checkout leaves today at 15:00');
if (!(await row.count())) throw new Error('no leaving time on Guest rooms');
await row.first().scrollIntoViewIfNeeded();
await p.screenshot({ path: `${OUT}/late-checkout-375.png` });
await b.close();
