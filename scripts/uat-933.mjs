// node scripts/uat-933.mjs — closing a day with bookings at 375x812 (#933). Against a throwaway seeded stack (E2E_BASE_URL).
import { chromium } from '@playwright/test';
import { mkdirSync } from 'node:fs';
const APP = process.env.E2E_BASE_URL || 'http://localhost:8093';
const OUT = 'docs/design/uat/2026-10-18-close-day-933';
mkdirSync(OUT, { recursive: true });
const { token } = await (await fetch(`${APP}/api/auth/login`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ email: 'admin@example.com', password: 'demo1234' }) })).json();
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 375, height: 812 }, hasTouch: true, isMobile: true });
await ctx.addInitScript((t) => { localStorage.setItem('authToken', t); localStorage.setItem('authRole', 'Admin'); }, token);
const p = await ctx.newPage();
await p.goto(`${APP}/admin/settings`); await p.waitForTimeout(2500);
await p.getByText(/Opening hours/).first().click(); await p.waitForTimeout(800);
await p.getByText(/Centre closed days|Closed days/).first().click(); await p.waitForTimeout(800);
await p.getByText(/Close another day/).click(); await p.waitForTimeout(500);
const day = new Date(Date.now() + 4 * 86400000).toISOString().slice(0, 10);
const dates = p.locator('input[type=date]');
await dates.nth(0).fill(day); await dates.nth(1).fill(day); await p.waitForTimeout(1500);
await p.screenshot({ path: `${OUT}/before-close-sheet.png` });
await p.getByRole('button', { name: /Close and move them/ }).click(); await p.waitForTimeout(1500);
await p.screenshot({ path: `${OUT}/after-moved-toast.png` });
await b.close();
