// node scripts/uat-1338.mjs — help links from sheet heads (#1338): Things to fix (s1) and Form C (s9), 375x812, on a throwaway stack (APP_URL).
import { chromium } from '@playwright/test';
import { mkdirSync } from 'node:fs';
const APP = process.env.APP_URL || 'http://localhost:8399';
const OUT = 'docs/design/uat/2026-10-30-help-from-refusals';
mkdirSync(OUT, { recursive: true });
const { token } = await (await fetch(`${APP}/api/auth/login`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ email: 'admin@example.com', password: 'demo1234' }) })).json();
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 375, height: 812 }, hasTouch: true, isMobile: true, timezoneId: 'Asia/Kolkata' });
await ctx.addInitScript((t) => { localStorage.setItem('authToken', t); localStorage.setItem('authRole', 'Admin'); localStorage.setItem('authUser', 'admin@example.com'); }, token);
const p = await ctx.newPage();
await p.goto(`${APP}/admin/settings`); await p.waitForTimeout(4000);
await p.getByRole('button', { name: 'Menu', exact: true }).last().click(); await p.waitForTimeout(800);
await p.getByText('Things to fix or decide').click({ force: true }); await p.waitForTimeout(1500);
await p.screenshot({ path: `${OUT}/things-to-fix-375.png` });
await p.goto(`${APP}/admin/patients`); await p.waitForTimeout(3000);
await p.getByText(/Form C/).first().click(); await p.waitForTimeout(1500);
await p.getByText(/Form C/).last().click(); await p.waitForTimeout(1500);
await p.screenshot({ path: `${OUT}/form-c-375.png` });
await b.close();
