// node scripts/uat-934.mjs <after> — Patients list with the Search chip, and a phone number found (#934), 375x812.
import { chromium } from '@playwright/test';
import { mkdirSync } from 'node:fs';
const APP = process.env.E2E_BASE_URL || 'http://localhost:8234';
const OUT = 'docs/design/uat/2026-10-18-find-patient-934';
mkdirSync(OUT, { recursive: true });
const { token } = await (await fetch(`${APP}/api/auth/login`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ email: 'admin@example.com', password: 'demo1234' }) })).json();
const pt = (await (await fetch(`${APP}/api/patients`, { headers: { Authorization: `Bearer ${token}` } })).json()).find((x) => x.phone);
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 375, height: 812 }, hasTouch: true, isMobile: true });
await ctx.addInitScript((t) => { localStorage.setItem('authToken', t); localStorage.setItem('authRole', 'Admin'); }, token);
const p = await ctx.newPage();
await p.goto(`${APP}/admin/patients`); await p.waitForTimeout(2500);
await p.screenshot({ path: `${OUT}/${process.argv[2] || 'after'}-list.png` });
await p.getByRole('button', { name: 'Search patients', exact: true }).click();
const [last, first] = pt.name.split(' ').reverse();
await p.keyboard.type(pt.phone.replace(/\D/g, '').slice(-6)); await p.waitForTimeout(1200);
await p.screenshot({ path: `${OUT}/${process.argv[2] || 'after'}-phone.png` });
await p.getByPlaceholder('Search patients').fill(`${last} ${first}`); await p.waitForTimeout(1200);
await p.screenshot({ path: `${OUT}/${process.argv[2] || 'after'}-surname-first.png` });
console.log(pt.name, pt.phone);
await b.close();
