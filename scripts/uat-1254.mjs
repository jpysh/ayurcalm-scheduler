// node scripts/uat-1254.mjs — what the doctor ruled out for a guest (#1254), 375x812, on a throwaway stack (APP_URL).
import { chromium } from '@playwright/test';
import { mkdirSync } from 'node:fs';
const APP = process.env.APP_URL || 'http://localhost:8391';
const OUT = 'docs/design/uat/2026-10-27-treatment-limits';
mkdirSync(OUT, { recursive: true });
const { token } = await (await fetch(`${APP}/api/auth/login`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ email: 'admin@example.com', password: 'demo1234' }) })).json();
const today = new Intl.DateTimeFormat('en-CA', { timeZone: 'Asia/Kolkata' }).format(new Date());
const add = (n) => new Date(Date.parse(`${today}T00:00:00Z`) + n * 86400000).toISOString().slice(0, 10);
await fetch(`${APP}/api/patients`, { method: 'POST', headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${token}` }, body: JSON.stringify({ name: 'Vamana Vani', gender: 'female', stay: { start_date: add(2), end_date: add(9) } }) });
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 375, height: 812 }, hasTouch: true, isMobile: true, timezoneId: 'Asia/Kolkata' });
await ctx.addInitScript((t) => { localStorage.setItem('authToken', t); localStorage.setItem('authRole', 'Admin'); localStorage.setItem('authUser', 'admin@example.com'); }, token);
const p = await ctx.newPage();
await p.goto(`${APP}/admin/patients`); await p.waitForTimeout(2500);
await p.getByRole('button', { name: /Vamana Vani/ }).first().click(); await p.waitForTimeout(1500);
await p.getByRole('dialog').getByRole('button', { name: /^Not for them/ }).click(); await p.waitForTimeout(1500);
await p.getByRole('textbox', { name: 'Why' }).fill('Vamana');
await p.getByRole('button', { name: /^Add / }).click(); await p.waitForTimeout(400);
await p.screenshot({ path: `${OUT}/not-for-them-375.png` });
await b.close();
