// node scripts/uat-1190.mjs — a returning guest's New stay with its guest room chosen in the same sheet (#1190), 375x812, on a throwaway stack (APP_URL).
import { chromium } from '@playwright/test';
import { mkdirSync } from 'node:fs';
const APP = process.env.APP_URL || 'http://localhost:8391';
const OUT = 'docs/design/uat/2026-10-26-new-stay-room';
mkdirSync(OUT, { recursive: true });
const { token } = await (await fetch(`${APP}/api/auth/login`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ email: 'admin@example.com', password: 'demo1234' }) })).json();
const api = (m, p, b) => fetch(`${APP}/api${p}`, { method: m, headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${token}` }, body: b ? JSON.stringify(b) : undefined }).then((r) => r.json());
await api('POST', '/patients', { name: 'Uat Returning Guest', gender: 'female', on_site: true, stay: { start_date: '2026-09-01', end_date: '2026-09-10' } });
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 375, height: 812 }, hasTouch: true, isMobile: true, timezoneId: 'Asia/Kolkata' });
await ctx.addInitScript((t) => { localStorage.setItem('authToken', t); localStorage.setItem('authRole', 'Admin'); localStorage.setItem('authUser', 'admin@example.com'); }, token);
const p = await ctx.newPage();
await p.goto(`${APP}/admin/patients`); await p.waitForTimeout(2500);
await p.getByRole('button', { name: 'Search patients' }).click();
await p.keyboard.type('Uat Returning'); await p.waitForTimeout(1200);
await p.getByText('Uat Returning Guest').first().click(); await p.waitForTimeout(1500);
await p.getByText('New stay', { exact: true }).first().click(); await p.waitForTimeout(2000);
if (!(await p.getByText('Guest room', { exact: true }).count())) throw new Error('the New stay sheet has no guest room line');
await p.screenshot({ path: `${OUT}/new-stay-with-room-375.png` });
await b.close();
