// node scripts/uat-1196-programme.mjs — a group's shared programme (#1196 part 3), 375x812, on a throwaway stack (APP_URL) with the group "Rishikesh Yoga".
import { chromium } from '@playwright/test';
import { mkdirSync } from 'node:fs';
const APP = process.env.APP_URL || 'http://localhost:8391';
const OUT = 'docs/design/uat/2026-10-27-group-programme';
mkdirSync(OUT, { recursive: true });
const { token } = await (await fetch(`${APP}/api/auth/login`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ email: 'admin@example.com', password: 'demo1234' }) })).json();
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 375, height: 812 }, hasTouch: true, isMobile: true, timezoneId: 'Asia/Kolkata' });
await ctx.addInitScript((t) => { localStorage.setItem('authToken', t); localStorage.setItem('authRole', 'Admin'); localStorage.setItem('authUser', 'admin@example.com'); }, token);
const p = await ctx.newPage();
await p.goto(`${APP}/admin/patients`); await p.waitForTimeout(2500);
await p.getByRole('button', { name: /^Groups/ }).click(); await p.waitForTimeout(800);
await p.getByRole('button', { name: /^Rishikesh Yoga\b/ }).first().click(); await p.waitForTimeout(1200);
await p.getByText('Programme for everyone').scrollIntoViewIfNeeded();
await p.screenshot({ path: `${OUT}/group-programme-375.png` });
await p.getByText('Add to the programme').click(); await p.waitForTimeout(800);
await p.getByRole('textbox', { name: 'What', exact: true }).fill('Abhyanga in turns');
await p.screenshot({ path: `${OUT}/add-to-programme-375.png` });
await b.close();
