// node scripts/uat-1173.mjs — the demo-password line over the day, then gone after a change (#1173), 375x812, on a throwaway stack (APP_URL).
import { chromium } from '@playwright/test';
import { mkdirSync } from 'node:fs';
const APP = process.env.APP_URL || 'http://localhost:8090';
const OUT = 'docs/design/uat/2026-10-26-demo-password-banner';
mkdirSync(OUT, { recursive: true });
const { token } = await (await fetch(`${APP}/api/auth/login`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ email: 'admin@example.com', password: 'demo1234' }) })).json();
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 375, height: 812 }, hasTouch: true, isMobile: true, timezoneId: 'Asia/Kolkata' });
await ctx.addInitScript((t) => { localStorage.setItem('authToken', t); localStorage.setItem('authRole', 'Admin'); localStorage.setItem('authUser', 'admin@example.com'); }, token);
const p = await ctx.newPage();
await p.goto(`${APP}/admin/schedule`); await p.waitForTimeout(2500);
await p.screenshot({ path: `${OUT}/day-banner-375.png` });
await p.getByRole('button', { name: 'Change it' }).click(); await p.waitForTimeout(1000);
await p.screenshot({ path: `${OUT}/account-sheet-375.png` });
await fetch(`${APP}/api/account/change-password`, { method: 'POST', headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${token}` }, body: JSON.stringify({ current_password: 'demo1234', new_password: 'uat-1173-changed' }) });
await p.goto(`${APP}/admin/schedule`); await p.waitForTimeout(2500);
if (await p.getByText("You're still using the demo password.").count()) throw new Error('the line stayed after the password changed');
await p.screenshot({ path: `${OUT}/day-after-change-375.png` });
await b.close();
