// node scripts/uat-1187.mjs — a guest room with guests ahead lists each with a free room to move to, and no Remove until none are left (#1187), 375x812, on a throwaway stack (APP_URL).
import { chromium } from '@playwright/test';
import { mkdirSync } from 'node:fs';
const APP = process.env.APP_URL || 'http://localhost:8186';
const OUT = 'docs/design/uat/2026-10-26-retire-moves-guests';
mkdirSync(OUT, { recursive: true });
const { token } = await (await fetch(`${APP}/api/auth/login`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ email: 'admin@example.com', password: 'demo1234' }) })).json();
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 375, height: 812 }, hasTouch: true, isMobile: true, timezoneId: 'Asia/Kolkata' });
await ctx.addInitScript((t) => { localStorage.setItem('authToken', t); localStorage.setItem('authRole', 'Admin'); localStorage.setItem('authUser', 'admin@example.com'); }, token);
const p = await ctx.newPage();
await p.goto(`${APP}/admin/guestrooms`); await p.waitForTimeout(2500);
await p.getByText('Names and beds').click(); await p.waitForTimeout(800);
await p.getByRole('button', { name: /^A1/ }).first().click(); await p.waitForTimeout(800);
await p.waitForTimeout(1500);
const list = p.getByText("Move these guests to remove it");
if (!(await list.count())) throw new Error("no guests listed");
if (await p.getByRole("button", { name: "Remove A1" }).count()) throw new Error("Remove offered with guests ahead");
await list.scrollIntoViewIfNeeded();
await p.screenshot({ path: `${OUT}/guests-to-move-375.png` });
await b.close();
