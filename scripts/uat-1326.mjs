// node scripts/uat-1297-save.mjs — Settings saved with an earlier closing time says how many treatments fall outside, and Fix them opens the day check (#1326), 375x812, throwaway stack (APP_URL).
import { chromium } from '@playwright/test';
import { mkdirSync } from 'node:fs';
const APP = process.env.APP_URL || 'http://localhost:8402';
const OUT = 'docs/design/uat/2026-10-27-shorter-hours';
mkdirSync(OUT, { recursive: true });
const { token } = await (await fetch(`${APP}/api/auth/login`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ email: 'admin@example.com', password: 'demo1234' }) })).json();
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 375, height: 812 }, hasTouch: true, isMobile: true, timezoneId: 'Asia/Kolkata' });
await ctx.addInitScript((t) => { localStorage.setItem('authToken', t); localStorage.setItem('authRole', 'Admin'); localStorage.setItem('authUser', 'admin@example.com'); }, token);
const p = await ctx.newPage();
await p.goto(`${APP}/admin/settings`); await p.waitForTimeout(2500);
await p.getByText(/Opening hours|Hours/).first().click(); await p.waitForTimeout(800);
await p.locator('select').nth(1).selectOption('17:00');
await p.getByRole('button', { name: 'Save', exact: true }).click(); await p.waitForTimeout(1500);
await p.screenshot({ path: `${OUT}/after-save-toast.png` });
await p.getByRole('button', { name: 'Fix them' }).click(); await p.waitForTimeout(4000);
console.log(p.url());
await p.screenshot({ path: `${OUT}/after-fix-them.png` });
await b.close();
