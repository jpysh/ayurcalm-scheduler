// node scripts/uat-1255.mjs — a late arrival on the stay sheet (#1255), 375x812, on a throwaway stack (APP_URL).
import { chromium } from '@playwright/test';
import { mkdirSync } from 'node:fs';
const APP = process.env.APP_URL || 'http://localhost:8391';
const OUT = 'docs/design/uat/2026-10-27-late-arrival';
mkdirSync(OUT, { recursive: true });
const { token } = await (await fetch(`${APP}/api/auth/login`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ email: 'admin@example.com', password: 'demo1234' }) })).json();
const today = new Intl.DateTimeFormat('en-CA', { timeZone: 'Asia/Kolkata' }).format(new Date());
const add = (n) => new Date(Date.parse(`${today}T00:00:00Z`) + n * 86400000).toISOString().slice(0, 10);
const p0 = await (await fetch(`${APP}/api/patients`, { method: 'POST', headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${token}` }, body: JSON.stringify({ name: 'Late Lata', gender: 'female', stay: { start_date: add(3), end_date: add(10) } }) })).json();
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 375, height: 812 }, hasTouch: true, isMobile: true, timezoneId: 'Asia/Kolkata' });
await ctx.addInitScript((t) => { localStorage.setItem('authToken', t); localStorage.setItem('authRole', 'Admin'); localStorage.setItem('authUser', 'admin@example.com'); }, token);
const p = await ctx.newPage();
await p.goto(`${APP}/admin/patients`); await p.waitForTimeout(2500);
await p.getByRole('button', { name: /Late Lata/ }).first().click(); await p.waitForTimeout(1500);
await p.getByRole('dialog').getByRole('button', { name: /^Dates/ }).click(); await p.waitForTimeout(1200);
await p.getByRole('button', { name: 'Arriving late…' }).click(); await p.waitForTimeout(600);
await p.getByText('Dinner is kept for them').scrollIntoViewIfNeeded();
await p.screenshot({ path: `${OUT}/stay-arriving-late-375.png`, fullPage: false });
await b.close();
