// node scripts/uat-973.mjs — several rooms and therapists added in one step (#973), 375x812, on a throwaway stack (E2E_BASE_URL) with ALLOW_DEMO_PASSWORD=true.
import { chromium } from '@playwright/test';
import { mkdirSync } from 'node:fs';
const APP = process.env.E2E_BASE_URL || 'http://localhost:8120';
const OUT = 'docs/design/uat/2026-10-22-bulk-add';
mkdirSync(OUT, { recursive: true });
const { token } = await (await fetch(`${APP}/api/auth/login`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ email: 'admin@example.com', password: 'demo1234' }) })).json();
const get = async (path) => (await fetch(`${APP}/api${path}`, { headers: { Authorization: `Bearer ${token}` } })).json();
const today = new Date().toLocaleDateString('en-CA', { timeZone: 'Asia/Kolkata' });
const problems = async () => JSON.stringify(await get(`/day-check?date=${today}`)).length;
const [rooms0, staff0, check0] = [(await get('/rooms')).length, (await get('/staff')).length, await problems()];
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 375, height: 812 }, hasTouch: true, isMobile: true, timezoneId: 'Asia/Kolkata' });
await ctx.addInitScript((t) => { localStorage.setItem('authToken', t); localStorage.setItem('authRole', 'Admin'); localStorage.setItem('authUser', 'admin@example.com'); }, token);
const p = await ctx.newPage();
const sheet = () => p.getByRole('dialog').last();
await p.goto(`${APP}/admin/rooms`); await p.waitForTimeout(2500);
await p.getByRole('button', { name: 'Add a room', exact: true }).click();
await p.waitForTimeout(800);
await sheet().getByRole('button', { name: 'Add several at once' }).click();
await sheet().getByLabel('Names, one a line').fill(Array.from({ length: 9 }, (_, i) => `Bulk Room ${i + 1}`).join('\n'));
await p.screenshot({ path: `${OUT}/rooms-375.png` });
await sheet().getByRole('button', { name: 'Add 9 rooms' }).click(); await p.waitForTimeout(2500);
await p.goto(`${APP}/admin/team`); await p.waitForTimeout(2500);
await p.getByRole('button', { name: 'Add a therapist or doctor', exact: true }).click();
await p.waitForTimeout(800);
await sheet().getByRole('button', { name: 'Add several at once' }).click();
await sheet().getByLabel('Names, one a line').fill('Bulk Asha\nBulk Ravi');
await sheet().getByRole('group', { name: 'Bulk Asha' }).getByRole('button', { name: 'Female', exact: true }).click();
await sheet().getByRole('group', { name: 'Bulk Ravi' }).getByRole('button', { name: 'Male', exact: true }).click();
await p.screenshot({ path: `${OUT}/therapists-375.png` });
await sheet().getByRole('button', { name: 'Add 2 therapists' }).click(); await p.waitForTimeout(2500);
const [rooms1, staff1, check1] = [(await get('/rooms')).length, (await get('/staff')).length, await problems()];
console.log(`rooms ${rooms0} -> ${rooms1}, staff ${staff0} -> ${staff1}, day check ${check0 === check1 ? 'unchanged' : 'CHANGED'}`);
await b.close();
