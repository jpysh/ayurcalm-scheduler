// node scripts/uat-1253.mjs — a double let as a single (#1253) on the accommodation sheet, 375x812, on a throwaway stack (APP_URL).
import { chromium } from '@playwright/test';
import { mkdirSync } from 'node:fs';
const APP = process.env.APP_URL || 'http://localhost:8391';
const OUT = 'docs/design/uat/2026-10-27-whole-room';
mkdirSync(OUT, { recursive: true });
const { token } = await (await fetch(`${APP}/api/auth/login`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ email: 'admin@example.com', password: 'demo1234' }) })).json();
const api = (m, p, b) => fetch(`${APP}/api${p}`, { method: m, headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${token}` }, body: b ? JSON.stringify(b) : undefined }).then((r) => r.json());
const today = new Intl.DateTimeFormat('en-CA', { timeZone: 'Asia/Kolkata' }).format(new Date());
const add = (n) => new Date(Date.parse(`${today}T00:00:00Z`) + n * 86400000).toISOString().slice(0, 10);
const dbl = (await api('GET', `/guest-rooms/free?from=${add(4)}&to=${add(9)}`)).find((r) => r.free && r.beds > 1);
await api('POST', '/patients', { name: 'Single Sita', gender: 'female', guest_room_id: dbl.id, stay: { start_date: add(4), end_date: add(9) } });
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 375, height: 812 }, hasTouch: true, isMobile: true, timezoneId: 'Asia/Kolkata' });
await ctx.addInitScript((t) => { localStorage.setItem('authToken', t); localStorage.setItem('authRole', 'Admin'); localStorage.setItem('authUser', 'admin@example.com'); }, token);
const p = await ctx.newPage();
await p.goto(`${APP}/admin/patients`); await p.waitForTimeout(2500);
await p.getByRole('button', { name: /Single Sita/ }).first().click(); await p.waitForTimeout(1500);
await p.getByRole('dialog').getByRole('button', { name: /^Accommodation/ }).click(); await p.waitForTimeout(1500);
await p.getByRole('switch', { name: 'The whole room for them' }).click(); await p.waitForTimeout(400);
await p.screenshot({ path: `${OUT}/whole-room-375.png` });
await b.close();
