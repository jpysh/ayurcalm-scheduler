// node scripts/uat-951.mjs — Day opening, sticky view control, therapist "all done" at 375x812 (#951, #938). Against a throwaway seeded stack (E2E_BASE_URL).
import { chromium } from '@playwright/test';
import { mkdirSync } from 'node:fs';
const APP = process.env.E2E_BASE_URL || 'http://localhost:8151';
const OUT = 'docs/design/uat/2026-10-18-day-open-951';
mkdirSync(OUT, { recursive: true });
const { token } = await (await fetch(`${APP}/api/auth/login`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ email: 'admin@example.com', password: 'demo1234' }) })).json();
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 375, height: 812 }, hasTouch: true, isMobile: true });
await ctx.addInitScript((t) => { localStorage.setItem('authToken', t); localStorage.setItem('authRole', 'Admin'); }, token);
const p = await ctx.newPage();
await p.goto(`${APP}/admin/schedule`); await p.waitForTimeout(3000);
await p.screenshot({ path: `${OUT}/after-open.png` });
console.log('scrollY on open', await p.evaluate(() => window.scrollY));
await p.evaluate(() => window.scrollTo(0, 700)); await p.waitForTimeout(500);
await p.screenshot({ path: `${OUT}/after-scrolled-sticky.png` });
await p.evaluate(() => window.scrollTo(0, 0));
await p.getByRole('button', { name: /^Show the day by/ }).click();
await p.getByRole('button', { name: 'Therapist', exact: true }).click(); await p.waitForTimeout(500);
await p.screenshot({ path: `${OUT}/after-by-therapist.png` });
await b.close();
