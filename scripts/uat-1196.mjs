// node scripts/uat-1196.mjs — a group booking: the Groups chip, the group's guests, and its dates moved in one action (#1196), 375x812, on a throwaway stack (APP_URL).
import { chromium } from '@playwright/test';
import { mkdirSync } from 'node:fs';
const APP = process.env.APP_URL || 'http://localhost:8391';
const OUT = 'docs/design/uat/2026-10-27-groups';
mkdirSync(OUT, { recursive: true });
const { token } = await (await fetch(`${APP}/api/auth/login`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ email: 'admin@example.com', password: 'demo1234' }) })).json();
const today = new Intl.DateTimeFormat('en-CA', { timeZone: 'Asia/Kolkata' }).format(new Date());
const add = (n) => new Date(Date.parse(`${today}T00:00:00Z`) + n * 86400000).toISOString().slice(0, 10);
for (const n of ['Anika Rao', 'Dev Malhotra', 'Isha Kapoor', 'Kabir Sethi', 'Lina Joseph']) await fetch(`${APP}/api/patients`, { method: 'POST', headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${token}` }, body: JSON.stringify({ name: n, gender: 'female', group_name: 'Rishikesh Yoga, Nov', stay: { start_date: add(10), end_date: add(17) } }) });
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 375, height: 812 }, hasTouch: true, isMobile: true, timezoneId: 'Asia/Kolkata' });
await ctx.addInitScript((t) => { localStorage.setItem('authToken', t); localStorage.setItem('authRole', 'Admin'); localStorage.setItem('authUser', 'admin@example.com'); }, token);
const p = await ctx.newPage();
await p.goto(`${APP}/admin/patients`); await p.waitForTimeout(2500);
await p.getByRole('button', { name: /^Groups/ }).click(); await p.waitForTimeout(1000);
await p.screenshot({ path: `${OUT}/groups-list-375.png` });
await p.getByText('Rishikesh Yoga, Nov').click(); await p.waitForTimeout(1200);
await p.getByLabel('Group arrives').fill(add(13)); await p.waitForTimeout(1000);
await p.screenshot({ path: `${OUT}/group-move-375.png` });
await b.close();
